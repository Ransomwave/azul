import fs from "node:fs";
import path from "node:path";
import { FileWriter } from "./fs/fileWriter.js";
import { log } from "./util/log.js";
import { isScriptClassName } from "./util/scriptFile.js";
import type { SourcemapNode, SourcemapRoot } from "./pack.js";

export const ROJO_PROJECT_FILE_NAME = "default.project.jsonc";

const DEFAULT_PROJECT_FILE_NAMES = [
  "default.project.json",
  "default.project.jsonc",
];

/**
 * Returns the project file Rojo would use for `dir`, if it has one.
 */
export function findDefaultProjectFile(dir: string): string | null {
  for (const name of DEFAULT_PROJECT_FILE_NAMES) {
    const candidate = path.join(dir, name);
    if (fs.existsSync(candidate)) return candidate;
  }
  return null;
}

const GENERATED_MARKER = "// @generated by Azul";

// Attribute Rojo reads to point a Ref property at the instance declaring that `$id`.
const REF_POINTER_PREFIX = "Rojo_Target_";

export interface RojoProjectOptions {
  /** Where the project will be written. `$path`s are relative to its folder. */
  projectFile: string;
  /** Directory the sourcemap's `filePaths` are relative to. */
  baseDir: string;
  syncDir: string;
  /** The project's name, unless it's rooted at a script (which names it). */
  name: string;
  /** Roots a model project here. Without it, the project is a place project. */
  packageRoot?: string;
}

type ProjectNode = Record<string, unknown>;

export interface RojoProject {
  name: string;
  emitLegacyScripts: boolean;
  tree: ProjectNode;
}

interface LocatedNode {
  node: SourcemapNode;
  path: string[];
}

interface SourcemapIndex {
  byGuid: Map<string, SourcemapNode>;
  byPath: Map<string, SourcemapNode>;
}

interface BuildContext {
  options: RojoProjectOptions;
  index: SourcemapIndex;
  /** Ids of the nodes another node in the project points at. */
  ids: Map<SourcemapNode, string>;
  inProject: Set<SourcemapNode>;
  clashes: string[];
}

const pathKey = (segments: string[]) => segments.join("\u0001");

/**
 * Builds a Rojo project describing every instance in a packed sourcemap
 * explicitly, rooted at `packageRoot` when one is given.
 * @throws If `packageRoot` isn't in the sourcemap, or an instance can't be
 * keyed in a project (same-named siblings, or a name starting with `$`).
 */
export function buildRojoProject(
  sourcemap: SourcemapRoot,
  options: RojoProjectOptions,
): RojoProject {
  const index = indexSourcemap(sourcemap);

  let root: LocatedNode;
  let name = options.name;

  if (options.packageRoot === undefined) {
    root = {
      node: {
        name: options.name,
        className: "DataModel",
        children: sourcemap.children,
      },
      path: [],
    };
  } else {
    const found = findPackageRootNode(sourcemap, options);
    if (!found) {
      throw new Error(
        `Package root ${options.packageRoot} isn't in the packed sourcemap. Point packageRoot at a folder or script inside a service.`,
      );
    }

    // A script pair is the package's single instance, as when pushing it. A
    // folder's contents land in a plain Folder, as the push destination does.
    if (isScriptClassName(found.node.className)) {
      root = found;
      name = found.node.name;
    } else {
      root = {
        node: {
          name: options.name,
          className: "Folder",
          children: found.node.children,
        },
        path: found.path,
      };
    }
  }

  const inProject = new Set<SourcemapNode>();
  const collect = (node: SourcemapNode) => {
    inProject.add(node);
    node.children?.forEach(collect);
  };
  collect(root.node);

  const ids = new Map<SourcemapNode, string>();
  for (const node of inProject) {
    for (const value of Object.values(node.properties ?? {})) {
      const target = resolveRef(value, index);
      if (target && inProject.has(target) && !ids.has(target)) {
        ids.set(target, target.guid ?? `azul-${ids.size}`);
      }
    }
  }

  const context: BuildContext = {
    options,
    index,
    ids,
    inProject,
    clashes: [],
  };
  const tree = describeNode(root.node, root.path, context);

  if (context.clashes.length > 0) {
    throw new Error(
      `Can't generate a Rojo project, since Rojo keys instances by name:\n${context.clashes
        .map((clash) => `  - ${clash}`)
        .join("\n")}\nRename these in Studio and pack again.`,
    );
  }

  return { name, emitLegacyScripts: true, tree };
}

/**
 * Writes a generated project, headed by a comment marking it as Azul's.
 */
export function writeRojoProject(
  project: RojoProject,
  projectFile: string,
  sourcemapPath: string,
): void {
  const sourcemap = toForwardSlashes(
    path.relative(path.dirname(projectFile), sourcemapPath),
  );
  const header = [
    `${GENERATED_MARKER} from "${sourcemap}" with "azul pack --rojo". Do not edit this file by hand!`,
    "// Requires Rojo 7.7.0+",
  ].join("\n");

  fs.mkdirSync(path.dirname(projectFile), { recursive: true });
  fs.writeFileSync(
    projectFile,
    `${header}\n${JSON.stringify(project, null, 2)}\n`,
    "utf8",
  );
}

/**
 * Whether `file` is a project Azul generated.
 */
export function isGeneratedRojoProject(file: string): boolean {
  try {
    return fs.readFileSync(file, "utf8").startsWith(GENERATED_MARKER);
  } catch {
    return false;
  }
}

function describeNode(
  node: SourcemapNode,
  nodePath: string[],
  context: BuildContext,
): ProjectNode {
  const description: ProjectNode = {};
  const filePath = node.filePaths?.[0];

  if (isScriptClassName(node.className) && filePath) {
    description.$path = toForwardSlashes(
      path.relative(
        path.dirname(context.options.projectFile),
        path.resolve(context.options.baseDir, filePath),
      ),
    );
  } else {
    description.$className = node.className;
    if (isScriptClassName(node.className)) {
      log.warn(
        `${nodePath.join(".")} has no script file, so it was added to the Rojo project without its source.`,
      );
    }
  }

  const id = context.ids.get(node);
  if (id !== undefined) description.$id = id;

  const properties: Record<string, unknown> = {};
  const attributes: Record<string, unknown> = { ...node.attributes };

  for (const [property, value] of Object.entries(node.properties ?? {})) {
    if (!isRef(value)) {
      properties[property] = value;
      continue;
    }

    const target = resolveRef(value, context.index);
    if (!target) continue;

    if (!context.inProject.has(target)) {
      log.warn(
        `${nodePath.join(".")}.${property} points outside of the Rojo project, so it was left out.`,
      );
      continue;
    }
    attributes[`${REF_POINTER_PREFIX}${property}`] = context.ids.get(target);
  }

  if (node.tags && node.tags.length > 0) properties.Tags = node.tags;

  if (Object.keys(properties).length > 0) description.$properties = properties;
  if (Object.keys(attributes).length > 0) description.$attributes = attributes;

  const seen = new Set<string>();
  for (const child of node.children ?? []) {
    const childPath = [...nodePath, child.name];

    if (child.name.startsWith("$")) {
      context.clashes.push(
        `${childPath.join(".")} starts with "$", which Rojo reserves for its own keys.`,
      );
      continue;
    }
    if (seen.has(child.name)) {
      context.clashes.push(
        `${nodePath.join(".") || node.name} has more than one child named "${child.name}".`,
      );
      continue;
    }

    seen.add(child.name);
    description[child.name] = describeNode(child, childPath, context);
  }

  return description;
}

function isRef(value: unknown): value is { Ref: unknown } {
  return value !== null && typeof value === "object" && "Ref" in value;
}

/**
 * Finds the node a packed Ref value points at, by GUID or else by path.
 */
function resolveRef(
  value: unknown,
  index: SourcemapIndex,
): SourcemapNode | null {
  if (!isRef(value) || !value.Ref || typeof value.Ref !== "object") {
    return null;
  }

  const { guid, path: refPath } = value.Ref as {
    guid?: unknown;
    path?: unknown;
  };

  if (typeof guid === "string") {
    const byGuid = index.byGuid.get(guid);
    if (byGuid) return byGuid;
  }

  if (Array.isArray(refPath)) {
    return index.byPath.get(pathKey(refPath.map(String))) ?? null;
  }

  return null;
}

function indexSourcemap(sourcemap: SourcemapRoot): SourcemapIndex {
  const byGuid = new Map<string, SourcemapNode>();
  const byPath = new Map<string, SourcemapNode>();

  const visit = (node: SourcemapNode, nodePath: string[]) => {
    if (node.guid) byGuid.set(node.guid, node);
    byPath.set(pathKey(nodePath), node);

    for (const child of node.children ?? []) {
      visit(child, [...nodePath, child.name]);
    }
  };

  for (const child of sourcemap.children ?? []) {
    visit(child, [child.name]);
  }

  return { byGuid, byPath };
}

/**
 * Finds the sourcemap node a package root stands for: the script a script file
 * or a script pair's folder belongs to, or else the instance a folder mirrors.
 */
function findPackageRootNode(
  sourcemap: SourcemapRoot,
  options: RojoProjectOptions,
): LocatedNode | null {
  const target = path.resolve(options.packageRoot!);
  const fileWriter = new FileWriter(options.syncDir);

  let scriptMatch: LocatedNode | null = null;
  let folderMatch: LocatedNode | null = null;

  const visit = (node: SourcemapNode, nodePath: string[]) => {
    const isScript = isScriptClassName(node.className);
    const ownsFile = node.filePaths?.some(
      (filePath) => path.resolve(options.baseDir, filePath) === target,
    );
    const mirrorsFolder =
      path.resolve(fileWriter.getDirPathForSegments(nodePath)) === target;

    if (isScript && (ownsFile || mirrorsFolder)) {
      scriptMatch ??= { node, path: nodePath };
    } else if (mirrorsFolder) {
      folderMatch ??= { node, path: nodePath };
    }

    for (const child of node.children ?? []) {
      visit(child, [...nodePath, child.name]);
    }
  };

  for (const child of sourcemap.children ?? []) {
    visit(child, [child.name]);
  }

  return scriptMatch ?? folderMatch;
}

function toForwardSlashes(filePath: string): string {
  return filePath.split(path.sep).join("/");
}
